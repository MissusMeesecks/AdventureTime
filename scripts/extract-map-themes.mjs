#!/usr/bin/env node
/**
 * Extract the Map Themes from the pinned legacy build (Phase 74g).
 *
 * Multihog's `src/state/map-themes.js` is the persistent maps' presentation:
 * the twenty-two colour fields in their four groups, the Ember default, the
 * five factory presets, the normalisers (a colour, a theme, the saved
 * presets), the preset resolver and the applier that writes the twenty-nine
 * `--rt-map-*` variables on a root. It imports nothing, so it is sliced
 * *whole* into one factory (CLAUDE.md 3a-bis), and `src/tracker/map-themes.ts`
 * is the typed face.
 *
 *   git clone --filter=blob:none \
 *     https://github.com/MultihogAurelius/SillyTavern-MultihogDnDFramework /tmp/mh
 *   git -C /tmp/mh checkout d6aab004f97f1f9a286f235de62f22ba1abadbe8
 *   node scripts/extract-map-themes.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/map-themes-legacy.js';
const FILE = 'src/state/map-themes.js';
/** The first line of code after the file comment; everything from here to the end is the module. */
const FROM = 'export const MAP_THEME_FIELDS';

/**
 * Every name the file exports, in source order, read from the source rather than remembered.
 * @param {string} source
 */
export function exportedNames(source) {
    return [...source.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((m) => m[1]);
}

/** @param {string} root */
export function sliceLegacy(root) {
    const source = readFileSync(`${root}/${FILE}`, 'utf8');
    const start = source.indexOf(FROM);
    if (start < 0) throw new Error(`${FILE} no longer contains: ${FROM}`);
    if (source.slice(0, start).includes('import ')) throw new Error(`${FILE} now imports something; it can no longer be sliced whole`);
    // Not dedented (lesson 36).
    return `// ── ${FILE} ──\n${source.slice(start).trim()}\n`.replace(/^export /gm, '');
}

if (process.argv[1] && process.argv[1].endsWith('extract-map-themes.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-map-themes.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the map themes must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const names = exportedNames(readFileSync(`${abs}/${FILE}`, 'utf8'));
    const header = `/**
 * GENERATED by scripts/extract-map-themes.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The Map Themes (\`src/state/map-themes.js\`, Phase 74g), sliced whole: the
 * fields, the Ember default, the five factory presets, the normalisers, the
 * preset resolver and the applier of the twenty-nine \`--rt-map-*\` variables. It
 * imports nothing and reads nothing from module scope (CLAUDE.md 3a-bis).
 * \`src/tracker/map-themes.ts\` is the typed face; \`map-themes.pin.test.ts\`
 * holds this file to a fresh slice of the pinned checkout and its behaviour
 * to the checkout's own module.
 */
/* eslint-disable */
// @ts-nocheck

export function createMapThemesLegacy() {
`;
    const footer = `
    return {
        ${names.join(',\n        ')},
    };
}
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source, ${names.length} exports)`);
}
