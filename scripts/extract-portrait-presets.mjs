#!/usr/bin/env node
/**
 * Extract the portrait prompt art styles from the pinned legacy build.
 *
 * Multihog's `src/state/portrait-prompts.js` is the Portrait Prompt
 * Library's grammar: the seven factory art styles (`FACTORY_PORTRAIT_PROMPT_PRESETS`),
 * the three system prompts each style is folded into (the NPC's, the
 * character's and the location's, with and without the present NPCs), the
 * two legacy location prompts, the reader that says whether a location
 * prompt is still a shipped one, and the reserved style names. It imports
 * nothing, so it is sliced *whole* into one factory (CLAUDE.md 3a-bis), and
 * `src/tracker/portrait-presets.ts` is the typed face.
 *
 *   git clone --filter=blob:none \
 *     https://github.com/MultihogAurelius/SillyTavern-MultihogDnDFramework /tmp/mh
 *   git -C /tmp/mh checkout d6aab004f97f1f9a286f235de62f22ba1abadbe8
 *   node scripts/extract-portrait-presets.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/portrait-presets-legacy.js';
const FILE = 'src/state/portrait-prompts.js';
/** The first line of the file; everything from here to the end is the library. */
const FROM = '/** Original 5.5.0 location prompt';

/**
 * Every name the file exports, in source order, read from the source rather than remembered.
 * @param {string} source
 */
export function exportedNames(source) {
    return [...source.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((m) => m[1]);
}

/** @param {string} root */
export function sliceLegacy(root) {
    const source = readFileSync(`${root}/${FILE}`, 'utf8');
    const start = source.indexOf(FROM);
    if (start < 0) throw new Error(`${FILE} no longer contains: ${FROM}`);
    if (/^import /m.test(source)) throw new Error(`${FILE} now imports something; it can no longer be sliced whole`);
    // Not dedented: a template literal is code, and an indent on every line
    // is an indent on every line of every prompt (lesson 36).
    return `// ── ${FILE} ──\n${source.slice(start).trim()}\n`.replace(/^export /gm, '');
}

if (process.argv[1] && process.argv[1].endsWith('extract-portrait-presets.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-portrait-presets.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the art styles must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const names = exportedNames(readFileSync(`${abs}/${FILE}`, 'utf8'));
    const header = `/**
 * GENERATED by scripts/extract-portrait-presets.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The Portrait Prompt Library's grammar (\`src/state/portrait-prompts.js\`),
 * sliced whole: it imports nothing and reads nothing from module scope
 * (CLAUDE.md 3a-bis). \`src/tracker/portrait-presets.ts\` is the typed face;
 * \`portrait-presets.pin.test.ts\` holds this file to a fresh slice of the
 * pinned checkout and its behaviour to the checkout's own module.
 */
/* eslint-disable */
// @ts-nocheck

export function createPortraitPresetsLegacy() {
`;
    const footer = `
    return {
        ${names.join(',\n        ')},
    };
}
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source, ${names.length} exports)`);
}
