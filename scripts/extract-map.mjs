#!/usr/bin/env node
/**
 * Extract the hidden-map document library from the pinned legacy build.
 *
 * Multihog's `dungeon-reality.js` is the grammar of a private objective map:
 * the v3 document (areas, connections, assets, knowledge), its parser,
 * normaliser, validator and serialiser, the prose the narrator and the player
 * are shown, the `[MAP]` section inside a Location entry, the Location
 * footer, which site the party is in, and the two prompt blocks the narrator
 * receives. It imports nothing, so it is sliced *whole* into one factory
 * (CLAUDE.md 3a-bis), and `src/tracker/map.ts` is the typed face over the
 * part each phase of row 9 uses.
 *
 *   git clone --filter=blob:none \
 *     https://github.com/MultihogAurelius/SillyTavern-MultihogDnDFramework /tmp/mh
 *   git -C /tmp/mh checkout d6aab004f97f1f9a286f235de62f22ba1abadbe8
 *   node scripts/extract-map.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/map-legacy.js';
const FILE = 'dungeon-reality.js';
/** The first line of code after the file comment; everything from here to the end is the library. */
const FROM = '// Some models incorrectly emit `</div hidden>`.';

/**
 * Every name the file exports, in source order, read from the source rather than remembered.
 * @param {string} source
 */
export function exportedNames(source) {
    return [...source.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((m) => m[1]);
}

/** @param {string} root */
export function sliceLegacy(root) {
    const source = readFileSync(`${root}/${FILE}`, 'utf8');
    const start = source.indexOf(FROM);
    if (start < 0) throw new Error(`${FILE} no longer contains: ${FROM}`);
    if (source.slice(0, start).includes('import ')) throw new Error(`${FILE} now imports something; it can no longer be sliced whole`);
    // Not dedented: a template literal is code, and an indent on every line
    // is an indent on every line of every prompt (lesson 36).
    return `// ── ${FILE} ──\n${source.slice(start).trim()}\n`.replace(/^export /gm, '');
}

if (process.argv[1] && process.argv[1].endsWith('extract-map.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-map.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the map document must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const names = exportedNames(readFileSync(`${abs}/${FILE}`, 'utf8'));
    const header = `/**
 * GENERATED by scripts/extract-map.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The hidden-map document library (\`dungeon-reality.js\`), sliced whole: it
 * imports nothing and reads nothing from module scope (CLAUDE.md 3a-bis).
 * \`src/tracker/map.ts\` is the typed face; \`map.pin.test.ts\` holds this file
 * to a fresh slice of the pinned checkout and its behaviour to the checkout's
 * own module.
 */
/* eslint-disable */
// @ts-nocheck

export function createMapLegacy() {
`;
    const footer = `
    return {
        ${names.join(',\n        ')},
    };
}
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source, ${names.length} exports)`);
}
