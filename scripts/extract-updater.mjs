/**
 * Extract the Map Updater's legacy half from the pinned build.
 *
 * Multihog's Map Updater keeps one attached map current with play: after a
 * reply inside a mapped site it asks a model for a transaction -- who moved,
 * what died, what was taken, which building the party entered -- validates
 * it against the document's rules (and the party invariant: a companion is
 * never a map asset), corrects it up to twice, and applies it. The *pure*
 * parts are sliced here, verbatim (CLAUDE.md 3a-bis): the two system prompts
 * (`map-updater-prompt.js`, `map-updater-direct-prompt.js`), the helper
 * library (`map-updater-lib.js`: the story window, the party roster, the two
 * party validators, the building-population validator), the prompt builders,
 * the operation summary and the noop check out of `map-updater.js`, and the
 * thread bookkeeping Map Evolution later reads out of `map-evolution-lib.js`.
 * The parts with I/O -- the model calls, the books, the commit -- are ported
 * by hand in `src/backend/map-updater.ts`.
 *
 *   node scripts/extract-updater.mjs /tmp/mh
 */
