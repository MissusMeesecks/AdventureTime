#!/usr/bin/env node
/**
 * Regenerates src/tracker/full-review-legacy.js from a checkout of the
 * pinned legacy build.
 *
 * Multihog's Full Review Mode (Phase 73c, departure 22) is two texts in
 * `src/state/defaults.js`: the Core Prompt that replaces the extractor's
 * while the mode is on, and the User Prompt Suffix that replaces the
 * suffix. They are module constants, not settings, so no cartridge
 * carries them; this imports the checkout's own module and writes the two
 * strings as it finds them, as scripts/extract-factory-defaults.mjs runs
 * the factory rather than transcribing it (CLAUDE.md 3a).
 *
 * Usage: node scripts/extract-full-review.mjs <path-to-upstream-checkout>
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

/** The commit docs/UPSTREAM.md pins. Extracting from anything else is refused. */
const PINNED = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';

export const SOURCE = 'src/state/defaults.js';
export const EXPORTS = ['FULL_REVIEW_STATE_SYSTEM_PROMPT', 'FULL_REVIEW_USER_PROMPT_SUFFIX'];

/**
 * The generated module's text from the checkout's own values.
 * @param {Record<string, string>} values
 * @param {string} head
 */
export function renderLegacy(values, head) {
    const lines = [
        '/**',
        ' * GENERATED by scripts/extract-full-review.mjs from',
        ` * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${head}.`,
        ' * Do not edit. Regenerate with the script; it refuses any other commit.',
        ' *',
        " * Multihog's Full Review Mode (departure 22, Phase 73c): the Core Prompt",
        " * and the User Prompt Suffix sent in place of the extractor's own while",
        ` * the mode is on, read from the checkout's \`${SOURCE}\` by import, not`,
        ' * transcribed. `full-review.pin.test.ts` holds this file to the checkout.',
        ' */',
        '/* eslint-disable */',
    ];
    for (const name of EXPORTS) lines.push(`export const ${name} = ${JSON.stringify(values[name])};`);
    return `${lines.join('\n')}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
    const upstreamDir = process.argv[2];
    if (!upstreamDir) {
        console.error('usage: node scripts/extract-full-review.mjs <path-to-upstream-checkout>');
        process.exit(2);
    }
    const abs = path.resolve(upstreamDir);
    const head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    if (head !== PINNED) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED}.`);
        process.exit(2);
    }
    const upstream = await import(pathToFileURL(path.join(abs, SOURCE)).href);
    const values = /** @type {Record<string, string>} */ ({});
    for (const name of EXPORTS) {
        if (typeof upstream[name] !== 'string' || !upstream[name].trim()) {
            console.error(`! ${SOURCE} exports no string named ${name}.`);
            process.exit(1);
        }
        values[name] = upstream[name];
    }
    const out = path.resolve('src/tracker/full-review-legacy.js');
    writeFileSync(out, renderLegacy(values, head));
    console.log(`wrote ${out} (${EXPORTS.length} exports)`);
}
