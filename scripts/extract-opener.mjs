#!/usr/bin/env node
/**
 * Extract the Map Architect's text opener from the pinned build (Phase 46).
 *
 * Multihog's alternative handshake for a connection that cannot call tools:
 * the narrator writes a `[CREATE_AREA_MAP] … [/CREATE_AREA_MAP]` block in its
 * reply instead of calling `CreateAreaMap`. `map-architect-opener.js` holds
 * the rules the mapping section carries in that mode, the CYOA caveat, the
 * setting's reader, the block's parser and the continue brief; it is sliced
 * whole here (CLAUDE.md 3a-bis) but for SillyTavern's own reasoning scrub,
 * and closed over the three things it reads from the map library. It is its
 * own file, not part of `architect-legacy.js`, because the rulebook reads the
 * rules and must not pull the map library into the frontend bundle for them.
 *
 *   node scripts/extract-opener.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/opener-legacy.js';

/** The slice runs from `from` to just before `to`. */
const SLICES = [
    ['map-architect-opener.js', "export const MAP_ARCHITECT_OPENER_TOOL = 'tool';", '/** Drop model thinking'],
];

/** @param {string} root */
export function sliceLegacy(root) {
    const out = [];
    for (const [file, from, to] of SLICES) {
        const source = readFileSync(`${root}/${file}`, 'utf8');
        const start = source.indexOf(from);
        if (start < 0) throw new Error(`${file} no longer contains: ${from}`);
        const end = source.indexOf(to, start + from.length);
        if (end < 0) throw new Error(`${file} no longer contains the end marker after: ${from}`);
        out.push(`// ── ${file}: ${from.slice(0, 48)} ──\n${source.slice(start, end).trim()}`);
    }
    // Not dedented: a template literal is code (lesson 36).
    return `${out.join('\n\n')}\n`.replace(/^export /gm, '');
}

if (process.argv[1] && process.argv[1].endsWith('extract-opener.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-opener.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the text opener must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const header = `/**
 * GENERATED by scripts/extract-opener.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The Map Architect's text opener (Phase 46): the mapping section's rules in
 * text mode, the CYOA caveat, the setting's reader, the [CREATE_AREA_MAP]
 * block's parser and the continue brief, sliced verbatim from the legacy
 * source and closed over the three things they read from the map library
 * (CLAUDE.md 3a-bis). \`src/tracker/opener.ts\` and \`src/tracker/architect.ts\`
 * are the typed faces; \`opener.pin.test.ts\` holds this file to a fresh slice
 * of the pinned checkout.
 */
/* eslint-disable */
// @ts-nocheck

/**
 * @param {{ normalizeMapSiteKind: Function, normalizeMapSiteThreat: Function, defaultMapSiteThreat: Function }} deps
 */
export function createOpenerLegacy({ normalizeMapSiteKind, normalizeMapSiteThreat, defaultMapSiteThreat }) {
`;
    const footer = `
    return {
        MAP_ARCHITECT_OPENER_TOOL, MAP_ARCHITECT_OPENER_TEXT, CREATE_AREA_MAP_OPEN_TAG, CREATE_AREA_MAP_CLOSE_TAG,
        MAP_ARCHITECT_TEXT_OPENER_CYOA_CAVEAT, MAP_ARCHITECT_TEXT_OPENER_RULES,
        isMapArchitectTextOpener, applyCyoaMapHandshakeCaveat, applyMapArchitectTextOpenerCyoaCaveat, normalizeMapArchitectOpener,
        parseCreateAreaMapCommand, createAreaMapCommandIsComplete, stripCreateAreaMapCommand,
        buildMapArchitectContinueBrief, seedMapArchitectContinueText,
    };
}
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source)`);
}
