#!/usr/bin/env node
/**
 * Extract the Map Architect's nested-map hosting from the pinned build
 * (Phase 58).
 *
 * Multihog hangs a child map inside a parent's area: `map-hosting.js` holds
 * the canonical peer path (`Parent :: Cell :: Child`), the host brief, the
 * stamp a hosted document carries (`hostSite`, `hostBrief`), the CORE mirror
 * of it, and the reparenting of a root's breadcrumbs; `map-hosting-context.js`
 * resolves a call's `attachTo` -- or the active cell as shorthand -- into the
 * host context the two prompts and the save read, with the host chain's
 * depth cap and the narrator's attachment errors; and `router.js` lends the
 * gateway asset's allocation and promotion on the parent map, and the root
 * entry lookup a hosted save uses. All sliced whole (CLAUDE.md 3a-bis) and
 * closed over the ten things they read from the map library.
 *
 *   node scripts/extract-hosting.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/hosting-legacy.js';

/**
 * [file, from, to]: the slice runs from `from` to just before `to` (the file's end for `null`).
 * @type {Array<[string, string, string | null]>}
 */
const SLICES = [
    ['map-hosting.js', '/** Maximum number of mapped documents in one host chain. */', null],
    ['map-hosting-context.js', 'export function normalizeMapAttachment(value) {', null],
    // The gateway asset's id, its promotion on the parent map, and the root entry lookup.
    ['router.js', 'function allocateHostedAssetId(document, name) {', '/**\n * Atomically attach a validated Map Architect document'],
    // The id's hash.
    ['router.js', 'function mapTransactionSignature(value) {', 'function resolveDungeonContextByUid('],
];

/** @param {string} root */
export function sliceLegacy(root) {
    const out = [];
    for (const [file, from, to] of SLICES) {
        const source = readFileSync(`${root}/${file}`, 'utf8');
        const start = source.indexOf(from);
        if (start < 0) throw new Error(`${file} no longer contains: ${from}`);
        const end = to === null ? source.length : source.indexOf(to, start + from.length);
        if (end < 0) throw new Error(`${file} no longer contains the end marker after: ${from}`);
        out.push(`// ── ${file}: ${from.slice(0, 48).replace(/\n/g, ' ')} ──\n${source.slice(start, end).trim()}`);
    }
    // Not dedented: a template literal is code (lesson 36).
    return `${out.join('\n\n')}\n`.replace(/^export /gm, '');
}

if (process.argv[1] && process.argv[1].endsWith('extract-hosting.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-hosting.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the hosting must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const header = `/**
 * GENERATED by scripts/extract-hosting.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The Map Architect's nested-map hosting (Phase 58): the canonical peer
 * path, the host brief, the stamp and its CORE mirror, the reparenting of
 * a root's breadcrumbs (\`map-hosting.js\`); the host context a call's
 * attachTo or the active cell resolves to, with the depth cap and the
 * narrator's attachment errors (\`map-hosting-context.js\`); and the gateway
 * asset's allocation and promotion on the parent map with the root entry
 * lookup (\`router.js\`), sliced verbatim from the legacy source and closed
 * over the ten things they read from the map library (CLAUDE.md 3a-bis).
 * \`src/tracker/hosting.ts\` is the typed face; \`hosting.pin.test.ts\` holds
 * this file to a fresh slice of the pinned checkout.
 */
/* eslint-disable */
// @ts-nocheck

/**
 * @param {{ getDungeonMapAttachment: Function, normalizeMapSiteKind: Function, parseDungeonMapDocument: Function, replaceDungeonMapSection: Function, serializeDungeonMapDocument: Function, dungeonLabelIdentitiesMatch: Function, dungeonSiteRootsMatch: Function, resolveActiveDungeonSite: Function, resolveCurrentMapPlacement: Function, resolveMapAreaIdentity: Function }} deps
 */
export function createHostingLegacy({ getDungeonMapAttachment, normalizeMapSiteKind, parseDungeonMapDocument, replaceDungeonMapSection, serializeDungeonMapDocument, dungeonLabelIdentitiesMatch, dungeonSiteRootsMatch, resolveActiveDungeonSite, resolveCurrentMapPlacement, resolveMapAreaIdentity }) {
`;
    const footer = `
    return {
        MAX_HOSTED_MAP_DEPTH,
        buildHostedPeerSitePath, reparentHostedLocationEntries, rebaseHostedMapDocuments, ensureHostCoreMirror,
        buildHostedPeerBrief, stampHostedPeerDocument,
        normalizeMapAttachment, resolveHostedCreationContext,
        allocateHostedAssetId, promoteHostedPeerAsset, findArchitectMapEntry, mapTransactionSignature,
    };
}
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source)`);
}
