#!/usr/bin/env node
/**
 * Extract the NPC library's helpers from the pinned legacy build.
 *
 * Multihog's global NPC library keeps identity cards — a campaign NPC's or
 * Player Card's `[CORE]` text, keywords and portrait — outside any chat, and
 * `npc-library-lib.js` is the pure half of it: the records, their unique
 * names, the identity extraction, the `.mnpc.json` package in and out, and
 * the two prompts that put a library card into play (Add to Party, Play as
 * PC). `src/ui/panel/card-synopsis.js` is the blurb the library's list shows
 * under a name. Both import nothing, so both are sliced *whole* into one
 * factory (CLAUDE.md 3a-bis), and `src/tracker/npc-library.ts` is the typed
 * face.
 *
 *   git clone --filter=blob:none \
 *     https://github.com/MultihogAurelius/SillyTavern-MultihogDnDFramework /tmp/mh
 *   git -C /tmp/mh checkout d6aab004f97f1f9a286f235de62f22ba1abadbe8
 *   node scripts/extract-npc-library.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/npc-library-legacy.js';
/** [file, the first line of code after the file comment]: everything from there to the end is sliced. */
export const FILES = [
    ['npc-library-lib.js', 'export const NPC_LIBRARY_FORMAT = '],
    ['src/ui/panel/card-synopsis.js', 'const NEXT_HEADER ='],
];

/**
 * Every name a file exports, in source order, read from the source rather than remembered.
 * @param {string} source
 */
export function exportedNames(source) {
    return [...source.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((m) => m[1]);
}

/** @param {string} root */
export function sliceLegacy(root) {
    const out = [];
    for (const [file, from] of FILES) {
        const source = readFileSync(`${root}/${file}`, 'utf8');
        const start = source.indexOf(from);
        if (start < 0) throw new Error(`${file} no longer contains: ${from}`);
        if (source.includes('\nimport ') || source.startsWith('import ')) throw new Error(`${file} now imports something; it can no longer be sliced whole`);
        // Not dedented: a template literal is code, and an indent on every
        // line is an indent on every line of every prompt (lesson 36).
        out.push(`// ── ${file} ──\n${source.slice(start).trim()}\n`.replace(/^export /gm, ''));
    }
    return out.join('\n');
}

/** @param {string} root */
export function allNames(root) {
    return FILES.flatMap(([file]) => exportedNames(readFileSync(`${root}/${file}`, 'utf8')));
}

if (process.argv[1] && process.argv[1].endsWith('extract-npc-library.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-npc-library.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the library must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const names = allNames(abs);
    const header = `/**
 * GENERATED by scripts/extract-npc-library.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The NPC library's helpers (\`npc-library-lib.js\`) and the card synopsis
 * (\`src/ui/panel/card-synopsis.js\`), sliced whole: neither imports anything
 * (CLAUDE.md 3a-bis). \`src/tracker/npc-library.ts\` is the typed face;
 * \`npc-library.pin.test.ts\` holds this file to a fresh slice of the pinned
 * checkout and its behaviour to the checkout's own modules.
 */
/* eslint-disable */
// @ts-nocheck

export function createNpcLibraryLegacy() {
`;
    const footer = `
    return {
        ${names.join(',\n        ')},
    };
}
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source, ${names.length} names)`);
}
