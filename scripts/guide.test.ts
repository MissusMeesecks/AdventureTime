/**
 * The guide's drift check.
 *
 * `guide/AdventureTime-guide.md` names what is on screen in bold, and nothing
 * else in bold. This test collects every bold phrase and fails unless each one
 * is a label in the extension's own source — a whole quoted string, comments
 * and tests aside — or is one of Lumiverse's own names on the list below. So a
 * label renamed in the code without the guide following fails here, naming the
 * phrase and the chapter that still uses the old name.
 *
 * It ships with the guide, so the public repository runs it too.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const GUIDE_PATH = 'guide/AdventureTime-guide.md'
/** The guide is sent whole to a model later, so its size is a budget. */
export const GUIDE_MAX_BYTES = 80 * 1024
/** The guide as the extension carries it, for the Adventure Companion: generated by `scripts/build-guide-text.mjs`. */
export const GUIDE_MODULE_PATH = 'src/backend/guide-text.ts'
const GUIDE_MODULE_NAME = 'guide-text.ts'

/**
 * Names that are Lumiverse's, not AdventureTime's, so the source need not
 * carry them. One line each, saying where in Lumiverse the name is.
 */
export const LUMIVERSE_NAMES: Record<string, string> = {
    'Prompt Breakdown': 'the per-message breakdown of what was sent to the model, opened from a reply',
    'Server Logs': 'the panel that lists the server’s log lines, extensions’ included',
    'Enable Function Calling': 'the switch on a connection that lets the model call tools',
}

export interface BoldPhrase {
    phrase: string
    chapter: string
    line: number
}

/** Every `**bold**` phrase of a Markdown text, with the heading it sits under. Code spans and fences are skipped. */
export function boldPhrases(markdown: string): BoldPhrase[] {
    const out: BoldPhrase[] = []
    let chapter = '(before the first heading)'
    let fenced = false
    let block: string[] = []
    let blockStart = 0
    // A paragraph or list item at a time, since a bold name may wrap onto the next line.
    const flush = (): void => {
        if (!block.length) return
        const text = block.join('\n').replace(/`[^`]*`/g, (span) => ' '.repeat(span.length))
        let last = 0
        for (const match of text.matchAll(/\*\*([\s\S]+?)\*\*/g)) {
            const line = blockStart + text.slice(0, match.index).split('\n').length
            out.push({ phrase: match[1].replace(/\s+/g, ' ').trim(), chapter, line })
            last = (match.index ?? 0) + match[0].length
        }
        // A `**` left over opens a bold that never closes: named, so it fails the check rather than hiding a phrase.
        const stray = text.indexOf('**', last)
        if (stray >= 0) out.push({ phrase: '(a bold that never closes)', chapter, line: blockStart + text.slice(0, stray).split('\n').length })
        block = []
    }
    markdown.split('\n').forEach((raw, index) => {
        if (/^\s*```/.test(raw)) { flush(); fenced = !fenced; return }
        if (fenced) return
        const heading = /^#{1,6}\s+(.*)$/.exec(raw)
        if (heading) { flush(); chapter = heading[1].trim(); return }
        if (!raw.trim()) { flush(); return }
        if (!block.length) blockStart = index
        block.push(raw)
    })
    flush()
    return out
}

/** A source file's text without its comments, so a name that survives only in a comment does not count as on screen. */
export function withoutComments(source: string): string {
    return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|\s)\/\/.*$/gm, '$1')
}

function sourceFiles(dir: string, out: string[] = []): string[] {
    for (const name of readdirSync(dir)) {
        const full = join(dir, name)
        if (statSync(full).isDirectory()) sourceFiles(full, out)
        // The guide's own text inside the extension is not a label: the guide cannot vouch for itself.
        else if (/\.(ts|js)$/.test(name) && !/\.test\.ts$/.test(name) && name !== GUIDE_MODULE_NAME) out.push(full)
    }
    return out
}

/**
 * Every string the source writes whole: the content of each quoted literal,
 * without a leading icon or a trailing colon. A label is a string of its own
 * (`'Run tracker now'`, `'⚡ Begin Instant Action'`); a name quoted inside a
 * help sentence is not, so a renamed label is not kept alive by the help text
 * that still mentions it.
 */
export function labelsOf(source: string): Set<string> {
    const labels = new Set<string>()
    const add = (raw: string): void => {
        if (!raw || raw.length > 120) return
        labels.add(raw)
        labels.add(raw.replace(/^[^\p{L}\p{N}]+/u, '').replace(/[:.…]+$/u, '').trim())
    }
    // Line by line, so a stray quote (a regex, an apostrophe in a template's text) spoils one line and not the file.
    for (const line of source.split('\n')) {
        // A button or heading written as HTML inside a template: its text between the tags is a label too.
        for (const tag of line.matchAll(/>([^<>{}$]{2,60})<\//g)) add(tag[1].trim())
        let at = 0
        while (at < line.length) {
            const quote = line[at]
            if (quote !== "'" && quote !== '"' && quote !== '`') { at += 1; continue }
            let end = at + 1
            let text = ''
            while (end < line.length && line[end] !== quote) {
                const escaped = /^\\u([0-9a-fA-F]{4})/.exec(line.slice(end, end + 6))
                if (escaped) { text += String.fromCharCode(parseInt(escaped[1], 16)); end += 6 }
                else if (line[end] === '\\' && end + 1 < line.length) { text += line[end + 1]; end += 2 } else { text += line[end]; end += 1 }
            }
            if (end >= line.length) break
            add(text)
            at = end + 1
        }
    }
    return labels
}

/** The phrases of `phrases` that are neither a label of `source` nor Lumiverse's own. */
export function driftedPhrases(phrases: readonly BoldPhrase[], source: string, allowed: Record<string, string> = LUMIVERSE_NAMES): BoldPhrase[] {
    const labels = labelsOf(source)
    return phrases.filter(({ phrase }) => !(phrase in allowed) && !labels.has(phrase))
}

const guide = readFileSync(join(ROOT, GUIDE_PATH), 'utf8')
const source = sourceFiles(join(ROOT, 'src')).map((file) => withoutComments(readFileSync(file, 'utf8'))).join('\n')

describe('the guide', () => {
    it('names in bold only what is on screen', () => {
        const phrases = boldPhrases(guide)
        expect(phrases.length).toBeGreaterThan(20)
        const drifted = driftedPhrases(phrases, source).map(({ phrase, chapter, line }) => `**${phrase}** (line ${line}, under “${chapter}”) is not a label anywhere in src/`)
        expect(drifted).toEqual([])
    })

    it('keeps no name on the Lumiverse list that it does not use', () => {
        const used = new Set(boldPhrases(guide).map(({ phrase }) => phrase))
        expect(Object.keys(LUMIVERSE_NAMES).filter((name) => !used.has(name))).toEqual([])
    })

    it('stays within its size budget', () => {
        expect(Buffer.byteLength(guide, 'utf8')).toBeLessThanOrEqual(GUIDE_MAX_BYTES)
    })

    it('carries none of the private project’s bookkeeping', () => {
        // No phase numbers, version numbers, dates or preference keys: the guide describes what is on screen.
        const prose = guide.replace(/```[\s\S]*?```/g, '').replace(/`[^`]*`/g, '')
        expect(prose).not.toMatch(/\bPhase \d/)
        expect(prose).not.toMatch(/\b1\.0\.0-(beta|rc)\.\d/)
        expect(prose).not.toMatch(/\b20\d\d-\d\d-\d\d\b/)
        expect(prose).not.toMatch(/\bdeparture \d/i)
    })

    it('lists every chapter it has in its table of contents, and no other', () => {
        const chapters = [...guide.matchAll(/^## (\d+\. .+)$/gm)].map((match) => match[1].trim())
        const contents = /^## Contents\n([\s\S]*?)\n## /m.exec(guide)?.[1] ?? ''
        const listed = [...contents.matchAll(/^\d+\. \[(.+?)\]\(#.+?\)$/gm)].map((match, index) => `${index + 1}. ${match[1]}`)
        expect(chapters.length).toBeGreaterThan(0)
        expect(listed).toEqual(chapters)
    })
})

/** GitHub's anchor for a heading: lower case, punctuation dropped, each space a hyphen. */
export function headingAnchor(heading: string): string {
    return heading.trim().toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-')
}

/** The `#anchor` of every link to the guide in a Markdown text; `own` reads the guide's links to itself. */
export function guideAnchors(markdown: string, own = false): string[] {
    const pattern = own ? /\]\(#([^)\s]+)\)/g : /\]\(guide\/AdventureTime-guide\.md#([^)\s]+)\)/g
    return [...markdown.matchAll(pattern)].map((match) => match[1])
}

describe('the guide’s list of the rulebook’s stock sections', () => {
    it('names every stock section the settings draw, and no other, so nobody is sent to a section that is not there', async () => {
        const { RULEBOOK_SECTION_LABELS } = await import('../src/frontend/rulebook-switches.js')
        const start = guide.indexOf('**Stock sections** are the rules that ship.')
        expect(start).toBeGreaterThan(0)
        const passage = guide.slice(start, guide.indexOf('A press on a section', start))
        const listed = boldPhrases(passage).map((b) => b.phrase).filter((name) => name !== 'Stock sections')
        expect(listed).toEqual(Object.values(RULEBOOK_SECTION_LABELS))
        expect(passage).toContain(`There are ${listed.length}, and this is the`)
    })
})

describe('the guide’s lists of the stock modules', () => {
    /** The italic names of a passage, in order: `*Name*`, never a bold. */
    const italics = (passage: string): string[] => Array.from(passage.matchAll(/(?<![*\w])\*([^*\n]+)\*(?!\*)/g), (m) => m[1]!)

    it('names every stock tracker module the settings list, and no other', async () => {
        const { FACTORY_CARTRIDGE_DEFAULTS } = await import('../src/state/factory-defaults.js') as { FACTORY_CARTRIDGE_DEFAULTS: Record<string, unknown> }
        const { buildTrackerModulesView } = await import('../src/settings/tracker-modules.js')
        const labels = buildTrackerModulesView(FACTORY_CARTRIDGE_DEFAULTS as never).rows.map((row) => row.label)
        const start = guide.indexOf('There are ten stock modules, and this is the whole list:')
        expect(start).toBeGreaterThan(0)
        const passage = guide.slice(start, guide.indexOf('*Settings → State Tracker → State Tracker', start))
        // Each list item opens with its module's name, or two names joined by "and".
        const listed = passage.split('\n').filter((line) => line.startsWith('- ')).flatMap((line) => italics(line.slice(0, line.indexOf(':'))))
        expect(listed).toEqual(labels)
        expect(labels).toHaveLength(10)
    })

    it('names every stock category of the Lorebook Agent, and no other', async () => {
        const { FACTORY_CARTRIDGE_DEFAULTS } = await import('../src/state/factory-defaults.js') as { FACTORY_CARTRIDGE_DEFAULTS: { routerModules: Record<string, { tag?: string }> } }
        const { moduleTag } = await import('../src/frontend/agent-modules.js')
        const tags = Object.entries(FACTORY_CARTRIDGE_DEFAULTS.routerModules).map(([key, module]) => moduleTag(key, module as never))
        const start = guide.indexOf('There are six\nstock categories, and this is the whole list:')
        expect(start).toBeGreaterThan(0)
        const passage = guide.slice(start, guide.indexOf('*WORLD* is World', start))
        expect(italics(passage)).toEqual(tags)
        expect(tags).toHaveLength(6)
    })
})

