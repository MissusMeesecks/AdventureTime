describe('the links into the guide', () => {
    const anchors = new Set([...guide.matchAll(/^#{1,6}\s+(.+)$/gm)].map((match) => headingAnchor(match[1])))

    it('point at headings the guide has, from the README and from the guide’s own contents', () => {
        const readme = readFileSync(join(ROOT, 'README.md'), 'utf8')
        const fromReadme = guideAnchors(readme)
        const fromGuide = guideAnchors(guide, true)
        expect(fromReadme.length).toBeGreaterThan(5)
        expect(fromGuide.length).toBeGreaterThan(5)
        expect([...fromReadme, ...fromGuide].filter((anchor) => !anchors.has(anchor))).toEqual([])
    })

    it('makes an anchor as GitHub does', () => {
        expect(headingAnchor('19. Playing without D&D')).toBe('19-playing-without-dd')
        // Each space is a hyphen of its own, so the hole a dropped character leaves shows as two.
        expect(headingAnchor('Rules & dice')).toBe('rules--dice')
        expect(headingAnchor('1. What AdventureTime is, and what it is not')).toBe('1-what-adventuretime-is-and-what-it-is-not')
        expect(guideAnchors('see [a](guide/AdventureTime-guide.md#7-dice) and [b](other.md#x) and [c](#local)')).toEqual(['7-dice'])
        expect(guideAnchors('see [c](#local) and [a](guide/AdventureTime-guide.md#7-dice)', true)).toEqual(['local'])
    })
})

describe('the drift check’s own parts', () => {
    it('reads bold phrases with their chapter, skipping code', () => {
        const found = boldPhrases('# Guide\n\n## 1. One\nPress **Go now**, then `**not this**`.\n```\n**nor this**\n```\n## 2. Two\n*Settings → **Deep***')
        expect(found).toEqual([
            { phrase: 'Go now', chapter: '1. One', line: 4 },
            { phrase: 'Deep', chapter: '2. Two', line: 9 },
        ])
    })

    it('reads a bold name that wraps onto the next line, and names a bold that never closes', () => {
        const found = boldPhrases('## 4. Four\n- Choose **High\n  agency** or **Normal**.\n\nThen **oops, no close.\n\nAnd **Fine**.')
        expect(found).toEqual([
            { phrase: 'High agency', chapter: '4. Four', line: 2 },
            { phrase: 'Normal', chapter: '4. Four', line: 3 },
            { phrase: '(a bold that never closes)', chapter: '4. Four', line: 5 },
            { phrase: 'Fine', chapter: '4. Four', line: 7 },
        ])
    })

    it('does not count a name that is only in a comment', () => {
        const text = withoutComments("/** The old Setup Guide. */\nconst a = 'Before you start' // was Setup Guide\nconst url = 'https://example.org/x'\n")
        expect(text).toContain('Before you start')
        expect(text).toContain('https://example.org/x')
        expect(text).not.toContain('Setup Guide')
    })

    it('names a phrase the source no longer has, and lets Lumiverse’s own names through', () => {
        const phrases = boldPhrases('## 3. Three\n**Kept** and **Renamed** and **Server Logs**')
        expect(driftedPhrases(phrases, "x = 'Kept'")).toEqual([{ phrase: 'Renamed', chapter: '3. Three', line: 2 }])
    })

    it('takes a label for a string of its own, an icon before it or not, and never a name inside a sentence', () => {
        const source = "a.textContent = '⚡ Begin now'\nb = 'Status:'\nhelp = 'Press Old name to begin, then Begin now.'"
        const labels = labelsOf(source)
        expect(labels.has('Begin now')).toBe(true)
        expect(labels.has('Status')).toBe(true)
        expect(labels.has('Old name')).toBe(false)
        // An escaped character is read as the character, and an HTML element's text counts.
        expect(labelsOf("back.textContent = '\\u2190'").has('←')).toBe(true)
        expect(labelsOf('return `<button type="button" title="${title}">Compact</button>`').has('Compact')).toBe(true)
        // A quote that never closes on its line gives no label, and spoils only that line.
        expect(labelsOf("const re = /it's/\nlabel = 'Fine'")).toEqual(new Set(['Fine']))
        expect(driftedPhrases(boldPhrases('## 1. One\n**Old name** then **Begin now**'), source)).toEqual([{ phrase: 'Old name', chapter: '1. One', line: 2 }])
    })
})
