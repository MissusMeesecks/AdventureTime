#!/usr/bin/env node
/**
 * Extract the narrator's stock rulebook from the pinned legacy build.
 *
 * Multihog's narrator system prompt is 22 stock sections (`<role>`,
 * `<rng_system>`, `<combat>`, `<resting>`, `<level_up_protocol>`, ...) held as
 * two template literals in `constants.js` -- `sysprompt.txt` (tool-call dice
 * wording) and `sysprompt_legacy.txt` (queue wording) -- plus the
 * `QUESTS_NARRATOR` block the quests section is rebuilt from.
 *
 * This EVALUATES those literals rather than regex-unescaping them: the text
 * carries forty escaped backticks and `${` sequences, and a hand transcription
 * of thirty thousand characters of rules is exactly the kind of copy that is
 * wrong in one line nobody reads. Same rule as `src/state/factory-defaults.js`
 * (CLAUDE.md 3a): generated from the pin, never edited by hand.
 *
 *   git clone --filter=blob:none \
 *     https://github.com/MultihogAurelius/SillyTavern-MultihogDnDFramework /tmp/mh
 *   git -C /tmp/mh checkout d6aab004f97f1f9a286f235de62f22ba1abadbe8
 *   node scripts/extract-rulebook.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/rulebook-text.js';

const dir = process.argv[2];
if (!dir) {
    console.error('usage: node scripts/extract-rulebook.mjs <upstream-checkout>');
    process.exit(2);
}
const abs = resolve(dir);
let head;
try {
    head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch (error) {
    console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(2);
}
if (head !== PINNED_COMMIT) {
    console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
    console.error('  Refusing: the rulebook must match the build the gate is pinned to.');
    process.exit(2);
}

const source = readFileSync(`${abs}/constants.js`, 'utf8');

/**
 * Evaluate one `'key': \`...\`` template literal out of the RT_PROMPTS table.
 * @param {string} key
 * @returns {string}
 */
function literal(key) {
    const open = source.indexOf(`'${key}': \``);
    if (open < 0) throw new Error(`no template literal for ${key}`);
    let at = open + key.length + 5;
    // Walk to the closing backtick, skipping escaped ones.
    let close = at;
    for (;;) {
        close = source.indexOf('`', close);
        if (close < 0) throw new Error(`unterminated literal for ${key}`);
        if (source[close - 1] !== '\\') break;
        close += 1;
    }
    // A real interpolation would be a bug here; the text carries only escapes.
    return new Function(`return \`${source.slice(at, close)}\``)();
}

/**
 * `export const NAME = \`...\`;`
 * @param {string} name
 * @returns {string}
 */
function exported(name) {
    const open = source.indexOf(`export const ${name} = \``);
    if (open < 0) throw new Error(`no export ${name}`);
    const at = open + `export const ${name} = \``.length;
    let close = at;
    for (;;) {
        close = source.indexOf('`', close);
        if (source[close - 1] !== '\\') break;
        close += 1;
    }
    return new Function(`return \`${source.slice(at, close)}\``)();
}

const toolCall = literal('sysprompt.txt');
const queue = literal('sysprompt_legacy.txt');
const questsNarrator = exported('QUESTS_NARRATOR');

/** @param {string} text */
const tags = (text) => [...text.matchAll(/^<([A-Za-z0-9_\[\]-]+)>$/gm)].map((m) => m[1]);

const banner = `/**
 * GENERATED by scripts/extract-rulebook.mjs from the pinned legacy build at
 * ${PINNED_COMMIT}. Do not hand-edit -- regenerate.
 *
 * The narrator's stock rulebook: Multihog's system prompt, in two variants
 * that differ in three lines (tool-call dice wording vs. the pre-seeded queue),
 * and the QUESTS_NARRATOR block the <quests> section is rebuilt from.
 *
 * tool-call variant: ${toolCall.length} chars, ${tags(toolCall).length} tagged blocks
 * queue variant:     ${queue.length} chars, ${tags(queue).length} tagged blocks
 */
`;

const out = banner
    + `export const RULEBOOK_TOOLCALL = ${JSON.stringify(toolCall)};\n\n`
    + `export const RULEBOOK_QUEUE = ${JSON.stringify(queue)};\n\n`
    + `export const QUESTS_NARRATOR = ${JSON.stringify(questsNarrator)};\n`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}`);
console.log(`  tool-call: ${toolCall.length} chars; queue: ${queue.length} chars; quests: ${questsNarrator.length} chars`);
console.log(`  top-level-looking tags: ${tags(toolCall).join(', ')}`);
