#!/usr/bin/env node
/**
 * Writes `src/backend/guide-text.ts` from `guide/AdventureTime-guide.md`.
 *
 * The Adventure Companion answers from the guide, so the guide has to be
 * inside the backend bundle. A plain import of the Markdown file does not
 * build, so the text is carried as a generated module, and
 * `scripts/guide.test.ts` fails when the module and the guide differ.
 *
 * Run it after every change to the guide:
 *
 *     node scripts/build-guide-text.mjs
 *
 * `--check` writes nothing and exits 1 when the module is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'guide', 'AdventureTime-guide.md')
const target = join(root, 'src', 'backend', 'guide-text.ts')

/**
 * The module's whole text for a guide's text. Exported for the test.
 * @param {string} markdown
 * @returns {string}
 */
export function guideModule(markdown) {
    return [
        '// Generated by scripts/build-guide-text.mjs from guide/AdventureTime-guide.md. Do not edit by hand:',
        '// change the guide and run the script. scripts/guide.test.ts holds the two to each other.',
        `export const GUIDE_TEXT: string = ${JSON.stringify(markdown)}`,
        '',
    ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const wanted = guideModule(readFileSync(source, 'utf8'))
    if (process.argv.includes('--check')) {
        let have = ''
        try { have = readFileSync(target, 'utf8') } catch { /* missing counts as out of date */ }
        if (have !== wanted) {
            console.error('src/backend/guide-text.ts is out of date. Run: node scripts/build-guide-text.mjs')
            process.exit(1)
        }
    } else {
        writeFileSync(target, wanted)
        console.log(`wrote src/backend/guide-text.ts (${wanted.length} characters)`)
    }
}
