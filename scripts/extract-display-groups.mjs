#!/usr/bin/env node
/**
 * Extract the Display Groups from the pinned legacy build (Phase 75).
 *
 * Multihog's `src/features/display-groups.js` is the display-only bundling
 * of module cards under one shared header: the excluded tags, the
 * normaliser (first group to claim a tag wins), the render plan (the members
 * present in a memo replaced by one virtual host at the first member's
 * position, in the group's own order), the mover that carries a group's
 * members through the section order together, and the virtual key. It
 * imports nothing, so it is sliced *whole* into one factory (CLAUDE.md
 * 3a-bis), with the group card's rules of `style.css` read as text;
 * `src/tracker/display-groups.ts` is the typed face.
 *
 *   git clone --filter=blob:none \
 *     https://github.com/MultihogAurelius/SillyTavern-MultihogDnDFramework /tmp/mh
 *   git -C /tmp/mh checkout d6aab004f97f1f9a286f235de62f22ba1abadbe8
 *   node scripts/extract-display-groups.mjs /tmp/mh
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PINNED_COMMIT = 'd6aab004f97f1f9a286f235de62f22ba1abadbe8';
const OUT = 'src/tracker/display-groups-legacy.js';
const FILE = 'src/features/display-groups.js';
const CSS = 'style.css';
/** The first line of code after the file comment; everything from here to the end is the module. */
const FROM = 'export const DISPLAY_GROUP_EXCLUDED_TAGS';
/** The group card's rules: from the body's rule up to the manager's, which is Multihog's popup and not drawn here. */
const CSS_FROM = '.rt-display-group-body {';
const CSS_TO = '.rt-display-group-options {';

/**
 * Every name the file exports, in source order, read from the source rather than remembered.
 * @param {string} source
 */
export function exportedNames(source) {
    return [...source.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((m) => m[1]);
}

/** @param {string} root */
export function sliceLegacy(root) {
    const source = readFileSync(`${root}/${FILE}`, 'utf8');
    const start = source.indexOf(FROM);
    if (start < 0) throw new Error(`${FILE} no longer contains: ${FROM}`);
    if (source.slice(0, start).includes('import ')) throw new Error(`${FILE} now imports something; it can no longer be sliced whole`);
    // Not dedented (lesson 36).
    return `// ── ${FILE} ──\n${source.slice(start).trim()}\n`.replace(/^export /gm, '');
}

/** The group card's stylesheet rules, as text. @param {string} root */
export function sliceCss(root) {
    const css = readFileSync(`${root}/${CSS}`, 'utf8');
    const start = css.indexOf(CSS_FROM);
    const end = css.indexOf(CSS_TO, start);
    if (start < 0 || end < 0) throw new Error(`${CSS} no longer holds the display group rules between ${CSS_FROM} and ${CSS_TO}`);
    return css.slice(start, end).trim();
}

if (process.argv[1] && process.argv[1].endsWith('extract-display-groups.mjs')) {
    const dir = process.argv[2];
    if (!dir) {
        console.error('usage: node scripts/extract-display-groups.mjs <upstream-checkout>');
        process.exit(2);
    }
    const abs = resolve(dir);
    let head;
    try {
        head = execFileSync('git', ['-C', abs, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    } catch (error) {
        console.error(`! ${abs} is not a git checkout: ${error instanceof Error ? error.message : String(error)}`);
        process.exit(2);
    }
    if (head !== PINNED_COMMIT) {
        console.error(`! checkout is at ${head}, not the pinned ${PINNED_COMMIT}.`);
        console.error('  Refusing: the display groups must match the build the gate is pinned to.');
        process.exit(2);
    }
    const body = sliceLegacy(abs);
    const names = exportedNames(readFileSync(`${abs}/${FILE}`, 'utf8'));
    const css = sliceCss(abs);
    const header = `/**
 * GENERATED by scripts/extract-display-groups.mjs from
 * MultihogAurelius/SillyTavern-MultihogDnDFramework @ ${PINNED_COMMIT}.
 * Do not edit. Regenerate with the script; it refuses any other commit.
 *
 * The Display Groups (\`src/features/display-groups.js\`, Phase 75), sliced
 * whole: the excluded tags, the normaliser, the render plan, the mover and
 * the virtual key. It imports nothing and reads nothing from module scope
 * (CLAUDE.md 3a-bis). The group card's rules of \`style.css\` follow as text.
 * \`src/tracker/display-groups.ts\` is the typed face;
 * \`display-groups.pin.test.ts\` holds this file to a fresh slice of the
 * pinned checkout and its behaviour to the checkout's own module.
 */
/* eslint-disable */
// @ts-nocheck

export function createDisplayGroupsLegacy() {
`;
    const footer = `
    return {
        ${names.join(',\n        ')},
    };
}

// ── ${CSS}: the group card ──
export const LEGACY_DISPLAY_GROUP_CSS = ${JSON.stringify(css)};
`;
    writeFileSync(OUT, `${header}${body}${footer}`);
    console.log(`wrote ${OUT} (${body.length} characters of legacy source, ${names.length} exports, ${css.length} characters of CSS)`);
}
