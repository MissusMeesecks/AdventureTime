export type LineIconName = keyof typeof SHAPES

export function lineIconSvg(name: LineIconName, size = 14): string {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${SHAPES[name]}</svg>`
}

/** A span holding the icon; decorative, so hidden from screen readers. */
export function lineIcon(el: El, name: LineIconName, size = 14): HTMLElement {
    const span = el('span', { class: `lh-icon lh-icon-${name}`, 'aria-hidden': 'true' })
    span.innerHTML = lineIconSvg(name, size)
    return span
}

