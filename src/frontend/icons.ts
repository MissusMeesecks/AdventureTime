/** Draw a card's icon: the line icon its title names, or the emoji it had when the title is not in the table. */
export function setCardIcon(span: HTMLElement, title: string, fallback: string, card = false): void {
    const name = (card ? CARD_ICONS[`${title} (card)`] : undefined) ?? CARD_ICONS[title]
    if (!name) { span.textContent = fallback; return }
    span.classList.add('lh-icon')
    span.innerHTML = lineIconSvg(name, 16)
}

