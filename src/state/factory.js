/**
 * The factory cartridge payload — the authority for the cartridge surface.
 *
 * `buildCartridgePayload` and `applyCartridgePayload` both iterate
 * `Object.keys(getFactoryCartridgePayload())`. That makes this module, and
 * not any live settings object, the definition of what a cartridge contains:
 *
 *   - a key here but missing from settings   -> exported at its factory value
 *   - a key here but missing from a cartridge -> restored at its factory value
 *   - a key *not* here                        -> invisible to cartridges entirely
 *
 * The last case is the dangerous one, and it is why CLAUDE.md rule 3 exists:
 * adding a setting to the cartridge surface means adding it to
 * CARTRIDGE_PAYLOAD_GROUPS, and the contract-lock test then fails until
 * EXPECTED_PAYLOAD_KEYS in tests/ is updated deliberately.
 *
 * The values come from src/state/factory-defaults.js, which is generated by
 * running the legacy build's own factory function (see
 * scripts/extract-factory-defaults.mjs). They are not transcribed by hand and
 * are not derived from anybody's saved configuration.
 *
 * This file stays plain .js on purpose: the frozen test suite imports
 * `../src/state/factory` and `../src/cartridges.js` by those exact paths, and
 * those imports must keep resolving without the suite being touched.
 */

import { CARTRIDGE_PAYLOAD_GROUPS, CARTRIDGE_PAYLOAD_KEYS } from './payload-groups.js';
import { FACTORY_CARTRIDGE_DEFAULTS } from './factory-defaults.js';

export { CARTRIDGE_PAYLOAD_GROUPS, CARTRIDGE_PAYLOAD_KEYS };

/**
 * Deep clone through JSON, deliberately.
 *
 * `structuredClone` would be the modern choice, but it is *not* equivalent
 * here: it preserves `undefined` properties, Dates, Maps and cycles, none of
 * which survive a cartridge's trip through `JSON.stringify` on export. The
 * legacy build cloned through JSON, so cloning through JSON is what keeps an
 * in-memory round trip and a wire round trip producing the same object.
 *
 * @template T
 * @param {T} value
 * @returns {T}
 */
function deepCloneJson(value) {
    return JSON.parse(JSON.stringify(value));
}

/**
 * Keys that must never be missing. Guards the one failure mode the generated
 * defaults could introduce: a key present in the schema but absent from the
 * extracted payload would make `applyCartridgePayload` write `undefined`.
 */
const missingDefaults = CARTRIDGE_PAYLOAD_KEYS.filter(
    (key) => FACTORY_CARTRIDGE_DEFAULTS[key] === undefined,
);
if (missingDefaults.length > 0) {
    throw new Error(
        `factory defaults are missing ${missingDefaults.length} payload key(s): ${missingDefaults.join(', ')}. ` +
        'Regenerate with scripts/extract-factory-defaults.mjs.',
    );
}

/**
 * Where AdventureTime's factory differs from Multihog's, deliberately (Phase 82,
 * the maintainer's decisions; `docs/DEPARTURES.md` carries each one). The
 * generated file stays the legacy's own, so the regeneration diff keeps
 * meaning something; the overrides are applied on the way out, and a key here
 * must be a payload key the generated file already holds.
 *
 * - `npcRelationshipBars`: the relationship system on from the first chat
 *   (2026-10-28). Multihog ships it off. Only a fresh install or a cartridge
 *   without the key sees it: a stored value, and a cartridge that carries the
 *   key, are kept as they are.
 *
 * @type {Readonly<Record<string, unknown>>}
 */
export const ADVENTURETIME_FACTORY_OVERRIDES = Object.freeze({
    npcRelationshipBars: true,
});

const unknownOverrides = Object.keys(ADVENTURETIME_FACTORY_OVERRIDES).filter(
    (key) => FACTORY_CARTRIDGE_DEFAULTS[key] === undefined,
);
if (unknownOverrides.length > 0) {
    throw new Error(`factory overrides name keys the generated defaults do not hold: ${unknownOverrides.join(', ')}`);
}

/**
 * A fresh, fully-populated factory payload. Always a deep copy: callers
 * mutate what they get back, and the defaults must not move underneath them.
 *
 * @returns {Record<string, unknown>}
 */
export function getFactoryCartridgePayload() {
    /** @type {Record<string, unknown>} */
    const payload = {};
    for (const key of CARTRIDGE_PAYLOAD_KEYS) {
        payload[key] = deepCloneJson(
            key in ADVENTURETIME_FACTORY_OVERRIDES ? ADVENTURETIME_FACTORY_OVERRIDES[key] : FACTORY_CARTRIDGE_DEFAULTS[key],
        );
    }
    return payload;
}
