/**
 * Generation wrappers.
 *
 * `spindle.generate.raw/quiet/batch` are direct provider calls, and they do
 * **not** resolve macros. Anything with `{{char}}` in it reaches the model
 * literally. That is risk R1 in the plan, and it is the nastiest kind of bug
 * to find later because nothing errors — the output is just quietly worse.
 *
 * So the extension does not call `spindle.generate.*` anywhere. It calls these
 * wrappers, which resolve every message through `spindle.macros.resolve()`
 * first and warn if anything macro-shaped survives.
 *
 * The legacy build leaned on SillyTavern's `substituteParams` in five files
 * plus its own macro layer. Funnelling every outbound call through one place
 * is what makes "did this prompt get its macros resolved?" answerable.
 */

import type { GenerationRequestDTO, LlmMessageDTO } from 'lumiverse-spindle-types'

import { describePassConnection, type PassConnection } from './narrator-connection.js'

/** The slice of `spindle.macros` this module needs. */
export interface MacroApi {
    resolve(
        template: string,
        options?: { chatId?: string; characterId?: string; userId?: string; commit?: boolean },
    ): Promise<{ text: string }>
}

/** The slice of `spindle.generate` this module needs. */
export interface GenerateApi {
    raw(input: GenerationRequestDTO): Promise<unknown>
    quiet(input: GenerationRequestDTO): Promise<unknown>
    batch(input: GenerationRequestDTO): Promise<unknown>
}

export interface LogApi {
    info(message: string): void
    warn(message: string): void
    error(message: string): void
}

/** Context a macro needs to resolve to anything character- or chat-specific. */
export interface MacroContext {
    chatId?: string
    characterId?: string
    userId?: string
}

/** Anything that still looks like an unresolved macro. */
const MACRO_PATTERN = /\{\{\s*[^{}]+\s*\}\}/g

/** List the macro-looking fragments left in a string. */
export function findUnresolvedMacros(text: string): string[] {
    return text.match(MACRO_PATTERN) ?? []
}

/**
 * Resolve macros in one message's content.
 *
 * Content is either a plain string or an array of parts, and only the text
 * parts can carry macros — image and audio parts are data, and tool parts are
 * generated by the model, so both are passed through untouched.
 */
async function resolveContent(
    content: LlmMessageDTO['content'],
    macros: MacroApi,
    context: MacroContext,
): Promise<LlmMessageDTO['content']> {
    if (typeof content === 'string') {
        const { text } = await macros.resolve(content, context)
        return text
    }

    if (!Array.isArray(content)) return content

    return Promise.all(
        content.map(async (part) => {
            if (part && part.type === 'text') {
                const { text } = await macros.resolve(part.text, context)
                return { ...part, text }
            }
            return part
        }),
    )
}

/**
 * Resolve macros across a whole message array.
 *
 * Messages resolve in parallel; they do not depend on each other, and a long
 * prompt stack would otherwise pay for each round trip in series.
 */
export async function resolveMessages(
    messages: LlmMessageDTO[],
    macros: MacroApi,
    context: MacroContext = {},
): Promise<LlmMessageDTO[]> {
    return Promise.all(
        messages.map(async (message) => ({
            ...message,
            content: await resolveContent(message.content, macros, context),
        })),
    )
}

/**
 * Warn about macro-shaped text that survived resolution.
 *
 * A warning, not an error. `{{` occurs in ordinary prose and in some prompt
 * formats, so refusing to send would be worse than the problem. What matters
 * is that a genuinely unresolved `{{char}}` leaves a trace in the log instead
 * of vanishing into the prompt.
 */
export function warnOnUnresolvedMacros(messages: LlmMessageDTO[], log: LogApi): string[] {
    const found: string[] = []
    for (const message of messages) {
        const text = typeof message.content === 'string'
            ? message.content
            : (message.content ?? [])
                .map((part) => (part && part.type === 'text' ? part.text : ''))
                .join('\n')
        found.push(...findUnresolvedMacros(text))
    }
    if (found.length > 0) {
        const unique = [...new Set(found)].slice(0, 8)
        log.warn(`unresolved macros in outbound prompt: ${unique.join(', ')}`)
    }
    return found
}

export interface GenerationDeps {
    generate: GenerateApi
    macros: MacroApi
    log: LogApi
    /**
     * Multihog's Debug Mode (72a): when it answers true for the user, every
     * request's messages and the reply go to the log in full, one line per
     * message. Absent, nothing is logged.
     */
    debug?: (userId?: string) => Promise<boolean>
    /**
     * The connection a request with no `connection_id` runs on (89): the
     * narrator's, by the resolver's chain. Absent, a blank row goes to the
     * host as it did, which is Lumiverse's default-ticked connection or a
     * refusal.
     */
    connection?: (chatId: string | undefined, userId: string | undefined) => Promise<PassConnection>
    /**
     * The output length for AdventureTime's own calls (89): sent as
     * `parameters.max_tokens` on every request that names none, when the
     * preference is set above zero. A preset's numbers never reach a quiet
     * call, so without it every pass runs at the provider's own default.
     */
    maxTokens?: (userId: string | undefined) => Promise<number>
}

/** A message's text for the log: the string, or the text parts joined. */
export function messageText(message: LlmMessageDTO): string {
    if (typeof message.content === 'string') return message.content
    return message.content.map((part) => ('text' in part && typeof part.text === 'string' ? part.text : `[${part.type}]`)).join('\n')
}

/** A generation request, minus the `type` the wrapper supplies. */
export type GenerationInput = Omit<GenerationRequestDTO, 'type'> & MacroContext

export interface Generation {
    raw(input: GenerationInput): Promise<unknown>
    quiet(input: GenerationInput): Promise<unknown>
    batch(input: GenerationInput): Promise<unknown>
}

/**
 * Build the macro-resolving generation wrappers.
 *
 * `chatId` and `characterId` are pulled off the input for macro resolution
 * and not forwarded — they are context for `macros.resolve`, not fields
 * `spindle.generate` accepts.
 */
export function createGeneration(deps: GenerationDeps): Generation {
    // The debug log's memory (72c-bis): the agent's loop resends the whole
    // conversation on every turn, and a log that printed all of it every
    // turn wrote the 20 KB system prompt once per turn — each copy longer
    // than the Server Logs' 150-line buffer, so a pressed pass pushed its
    // own opening out of view before it finished. A request whose messages
    // begin with the ones logged last, and go on past them, logs the tail
    // alone and says so; a fresh pass logs whole.
    const logged = new Map<string, string[]>()
    const LOGGED_KEYS = 32
    // The connection lines (89): one per key within the window, the oldest forgotten.
    const saidAt = new Map<string, number>()
    const SAY_WINDOW_MS = 5_000
    function sayOnce(key: string, line: string): void {
        const now = Date.now()
        const last = saidAt.get(key)
        if (last !== undefined && now - last < SAY_WINDOW_MS) return
        saidAt.delete(key)
        saidAt.set(key, now)
        while (saidAt.size > LOGGED_KEYS) {
            const oldest = saidAt.keys().next().value
            if (oldest === undefined) break
            saidAt.delete(oldest)
        }
        deps.log.info(line)
    }
    function newSince(key: string, texts: string[]): number {
        const previous = logged.get(key) ?? []
        const continues = texts.length > previous.length && previous.every((text, i) => text === texts[i])
        logged.delete(key)
        logged.set(key, texts)
        while (logged.size > LOGGED_KEYS) {
            const oldest = logged.keys().next().value
            if (oldest === undefined) break
            logged.delete(oldest)
        }
        return continues ? previous.length : 0
    }

    async function dispatch(type: GenerationRequestDTO['type'], input: GenerationInput): Promise<unknown> {
        const { chatId, characterId, ...request } = input
        const context: MacroContext = { chatId, characterId, userId: input.userId }

        const messages = request.messages
            ? await resolveMessages(request.messages, deps.macros, context)
            : undefined

        if (messages) warnOnUnresolvedMacros(messages, deps.log)

        // AdventureTime's own calls — the tracker, the agent, the world, the maps,
        // the creator — read text, never a function call. With function
        // calling on for the connection the host may offer the chat's tools
        // to a quiet generation too, and a model in tool mode then answers
        // the agent's text tools as function calls the host renders as
        // `<button-pressed>` stubs (45c-bis, lesson 51). So a quiet or batch
        // request carries no tools unless its caller named some.
        const tools = type === 'raw' ? request.tools : (request.tools ?? [])

        // A blank connection means the narrator's (89), and every pass says what it ran on and why,
        // once per short while per chat and connection so the agent's loop does not repeat it each turn.
        if (!request.connection_id && deps.connection) {
            const resolved = await deps.connection(chatId, input.userId).catch(() => null)
            if (resolved?.id) request.connection_id = resolved.id
            if (resolved) sayOnce(`${input.userId ?? ''}\n${chatId ?? ''}\n${resolved.id ?? ''}\n${resolved.why}`, `connection: ${type} generation${chatId ? ` for chat ${chatId}` : ''} runs on ${describePassConnection(resolved)}`)
        } else if (request.connection_id) {
            sayOnce(`${input.userId ?? ''}\n${chatId ?? ''}\n${request.connection_id}\nchosen`, `connection: ${type} generation${chatId ? ` for chat ${chatId}` : ''} runs on ${request.connection_id} — chosen on its row under Connections & models`)
        }
        // The output length (89): the preference, where the caller named none.
        const parameters = request.parameters as Record<string, unknown> | undefined
        if (deps.maxTokens && (!parameters || parameters.max_tokens === undefined)) {
            const limit = await deps.maxTokens(input.userId).catch(() => 0)
            if (limit > 0) request.parameters = { ...parameters, max_tokens: limit }
        }
        const verbose = deps.debug ? await deps.debug(input.userId).catch(() => false) : false
        if (verbose) {
            const connection = request.connection_id ? ` on connection ${request.connection_id}` : ''
            const texts = (messages ?? []).map((message) => `${message.role}\n${messageText(message)}`)
            const since = newSince(`${input.userId ?? ''}\n${chatId ?? ''}\n${type}`, texts)
            deps.log.info(`debug: ${type} generation${connection}, ${messages?.length ?? 0} messages${tools?.length ? `, ${tools.length} tools` : ''}${since ? ` (the first ${since} as logged above)` : ''}`)
            for (const [i, message] of (messages ?? []).entries()) if (i >= since) deps.log.info(`debug: message ${i + 1} [${message.role}]\n${messageText(message)}`)
        }
        const result = await deps.generate[type]({ ...request, type, messages, ...(tools !== undefined ? { tools } : {}) })
        if (verbose) {
            let text: string
            try { text = typeof result === 'string' ? result : JSON.stringify(result) } catch { text = String(result) }
            deps.log.info(`debug: ${type} reply\n${text}`)
        }
        return result
    }

    return {
        raw: (input) => dispatch('raw', input),
        quiet: (input) => dispatch('quiet', input),
        batch: (input) => dispatch('batch', input),
    }
}
